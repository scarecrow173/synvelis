//! Typed Action Recipe → atomic batch lowering (SV-SCRIPT-02 /
//! synvelis#272, canonical contract `docs/automation/design-script.md`
//! + `docs/automation/design-atomic-macro.md`).
//!
//! [`compile_action_recipe`] is the *only* bridge from a script-side
//! [`synvelis_script::ActionRecipe`] into the AUTX-04 batch path. It
//! translates the recipe's resolved members into an
//! [`AtomicMacroDefinition`] whose steps carry the members' exact
//! capability pins, literal args, and literal targets, then runs the
//! unchanged [`MacroCompiler::compile`] — capability availability,
//! `ProjectMutation` + `Sync` domain/execution checks, schema
//! validation, target-contract checks, effect/data-access ceilings,
//! nested-batch rejection, and the 64-member bound all stay owned by
//! the macro compiler. Nothing here prepares, authorizes, commits, or
//! mints identity; the resulting [`CompiledMacro::batch_args`] still
//! flows through `synvelis.operation.prepare` → GW-05 approval →
//! GW-06 commit as one `ProjectOp::Composite`.
//!
//! Create-then-reference (`$output.` bindings / non-empty `bindings[]`)
//! is *not* generated by this bridge: recipe members carry concrete,
//! already-resolved args and targets — a script cannot name a resource
//! id that does not exist yet. Binding semantics remain AUTX-04/GW-04
//! owned; the gateway's non-empty-`bindings` rejection is untouched.

use serde_json::{Map, json};
use synvelis_script::{ActionRecipe, ActionRecipeKind, ScriptTarget};

use crate::CompiledMacro;
use crate::error::AutomationError;
use crate::expr::Expr;
use crate::macros::{
    AtomicMacroDefinition, MACRO_SCHEMA_VERSION, MacroCompiler, MacroPolicy, MacroStep,
};
use crate::refs::VersionedRef;
use crate::registry::RegistrySnapshot;

/// Compiles a batch [`ActionRecipe`] into the flat
/// `synvelis.operation.batch` member list via the unchanged AUTX-04
/// [`MacroCompiler`].
///
/// The recipe's members become literal-only macro steps (`m0`, `m1`,
/// …): exact `capability@major.minor` pins, concrete args (already
/// lowered + schema-validated by the script binding surface), and
/// literal targets. The recipe's pinned `expected-revision` consistency
/// is echoed into the artifact for the caller's consistency binding.
///
/// # Errors
/// [`AutomationError::Definition`] — the recipe is not a batch recipe
/// (single-member recipes lower through `ActionRecipe::to_draft`,
/// never through the batch compiler); any [`AutomationError::Compile`]
/// rejection the macro compiler produces — unknown/unavailable
/// capability, wrong domain/execution, schema or target violation,
/// nested batch, member-count overflow — fail-closed, all-or-nothing.
pub fn compile_action_recipe(
    recipe: &ActionRecipe,
    registry: &RegistrySnapshot,
) -> Result<CompiledMacro, AutomationError> {
    if recipe.kind() != ActionRecipeKind::Batch {
        return Err(AutomationError::Definition {
            reason: format!(
                "compile_action_recipe requires a batch recipe, got {} ({} member(s))",
                recipe.kind().as_str(),
                recipe.members.len()
            ),
        });
    }
    let steps = recipe
        .members
        .iter()
        .enumerate()
        .map(|(index, member)| MacroStep {
            id: format!("m{index}"),
            capability: VersionedRef::new(
                member.capability.id.as_str(),
                member.capability.version.major,
                member.capability.version.minor,
            ),
            args: Expr::Literal {
                value: member.args.clone(),
            },
            target: member.target.as_ref().map(script_target_expr),
        })
        .collect();
    let definition = AtomicMacroDefinition {
        schema_version: MACRO_SCHEMA_VERSION,
        macro_id: recipe.script_id.clone(),
        version: recipe.script_version,
        parameters: Vec::new(),
        steps,
        output_bindings: Vec::new(),
        policy: MacroPolicy::default(),
    };
    MacroCompiler::compile(
        &definition,
        &Map::new(),
        registry,
        recipe.expected_revision(),
    )
}

/// Lowers a script [`ScriptTarget`] to the literal `Expr` the macro
/// target contract expects: the tagged id string for `resource` /
/// `create` (parent id), the id array for `resource-set`. Kind
/// agreement was already enforced by the script binding surface
/// against the Gateway contract; the macro compiler re-validates the
/// concrete id against *its* snapshot's declared contract — a
/// disagreement between the two snapshot views is a typed rejection,
/// which is exactly the drift detection this layering wants.
fn script_target_expr(target: &ScriptTarget) -> Expr {
    let value = match target {
        ScriptTarget::Resource { id, .. } => json!(id),
        ScriptTarget::ResourceSet { ids, .. } => json!(ids),
        ScriptTarget::Create { parent, .. } => json!(parent),
    };
    Expr::Literal { value }
}
